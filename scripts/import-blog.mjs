// Import posts from the Storytelling repository (gardlae/Storytelling) into the blog.
//
//   node scripts/import-blog.mjs [path to Storytelling]          # default ~/Berkeley/Storytelling
//   node scripts/import-blog.mjs [path] --drafts                   # local look at candidates (dev server only)
//
// Only posts whose metadata.json status is approved, scheduled or published are imported, unless the
// metadata sets "website": false. Writes app/content/blog-posts.ts and public/blog/<slug>/ (graphic and
// carousel). Never edits the Storytelling repository. With --drafts, candidates are imported too and marked
// draft: production builds drop them and the content check refuses them, so do not commit that output.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const drafts = args.includes("--drafts");
const source = resolve(args.find((a) => !a.startsWith("--")) ?? join(homedir(), "Berkeley", "Storytelling"));
const PUBLIC_STATES = new Set(["approved", "scheduled", "published"]);

if (!existsSync(join(source, "posts")) || !existsSync(join(source, "brand"))) {
  console.error(`import-blog: ${source} does not look like the Storytelling repository (no posts/ and brand/)`);
  process.exit(1);
}

function pngSize(path) {
  const b = readFileSync(path);
  if (b.toString("ascii", 1, 4) !== "PNG") return null;
  return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
}

function linkedInText(markdown) {
  const title = (markdown.match(/^#\s+(.+)$/m) ?? [])[1]?.trim() ?? "";
  const start = markdown.indexOf("## LinkedIn text");
  if (start < 0) return { title, paragraphs: [] };
  const rest = markdown.slice(start + "## LinkedIn text".length);
  const end = rest.search(/^##\s/m);
  const body = (end < 0 ? rest : rest.slice(0, end)).trim();
  const paragraphs = body.split(/\n\s*\n/).map((p) => p.replace(/\s*\n\s*/g, " ").trim()).filter(Boolean);
  return { title, paragraphs };
}

const posts = [];
for (const id of readdirSync(join(source, "posts")).sort()) {
  const dir = join(source, "posts", id);
  const metaPath = join(dir, "metadata.json");
  if (!existsSync(metaPath)) continue;
  const meta = JSON.parse(readFileSync(metaPath, "utf8"));
  const isPublic = PUBLIC_STATES.has(meta.status) && meta.website !== false;
  if (!isPublic && !(drafts && meta.status === "candidate")) continue;

  const { title, paragraphs } = linkedInText(readFileSync(join(dir, "post.md"), "utf8"));
  // the LinkedIn hook usually repeats the title, which the page already shows
  const norm = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
  if (paragraphs.length > 1 && norm(paragraphs[0]) === norm(meta.title || title)) paragraphs.shift();
  if (!paragraphs.length) continue;
  const slug = id.replace(/^\d+-/, "");
  const out = join(root, "public", "blog", slug);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });

  const post = {
    slug,
    id,
    title: meta.title || title,
    date: (meta.publication?.published_at || meta.review?.approved_at || meta.created_at || "").slice(0, 10),
    status: meta.status,
    summary: paragraphs[0],
    paragraphs,
  };
  const graphic = join(dir, "exports", "graphic.png");
  if (existsSync(graphic)) {
    copyFileSync(graphic, join(out, "graphic.png"));
    let alt = post.title;
    const storyboard = join(dir, "storyboard.json");
    if (existsSync(storyboard)) alt = JSON.parse(readFileSync(storyboard, "utf8")).graphic?.alt_text || alt;
    post.graphic = { src: `/blog/${slug}/graphic.png`, alt, ...(pngSize(graphic) ?? { width: 1080, height: 1350 }) };
  }
  const carousel = join(dir, "exports", "carousel.pdf");
  if (existsSync(carousel)) {
    copyFileSync(carousel, join(out, "carousel.pdf"));
    post.carousel = `/blog/${slug}/carousel.pdf`;
  }
  if (meta.publication?.url) post.linkedin = meta.publication.url;
  if (!isPublic) post.draft = true;
  posts.push(post);
}

// remove folders of posts that are no longer imported
const blogDir = join(root, "public", "blog");
if (existsSync(blogDir)) {
  for (const name of readdirSync(blogDir)) {
    if (!posts.some((p) => p.slug === name)) rmSync(join(blogDir, name), { recursive: true, force: true });
  }
}

posts.sort((a, b) => b.date.localeCompare(a.date) || b.id.localeCompare(a.id));
writeFileSync(
  join(root, "app", "content", "blog-posts.ts"),
  "// Generated by scripts/import-blog.mjs from the Storytelling repository. Do not edit by hand.\n" +
    'import type { BlogPost } from "./types";\n\n' +
    `export const blogPosts: BlogPost[] = ${JSON.stringify(posts, null, 2)};\n`,
);
const draftCount = posts.filter((p) => p.draft).length;
console.log(`import-blog: ${posts.length - draftCount} public post(s)` +
  (draftCount ? `, ${draftCount} draft(s) for local viewing only: do not commit this output` : "") + ` from ${source}`);
